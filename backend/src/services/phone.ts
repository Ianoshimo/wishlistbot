// Аудит 2026-10-08, А-18: одно правило номера для СБП на фронте и бэке.
// Раньше бэк проверял символы и длину СТРОКИ (`/^[\d\s()+-]{10,20}$/`), а
// фронт - число цифр: "8.900.123.45.67" фронт пропускал, API отвечал 400, и
// пользователь видел общее "Проверьте введённые данные". Теперь оба
// нормализуют номер к +7XXXXXXXXXX: оставляем цифры, 8/7 в начале
// 11-значного номера - код России, 10 цифр - номер без кода. СБП работает
// только с российскими номерами, поэтому другие форматы - ошибка.
// Та же функция - frontend/src/phone.ts (держать одинаковыми).

// Разрешённые разделители: пробел, скобки, дефис, точка, плюс.
const ALLOWED = /^[\d\s()+\-.]{1,30}$/;

export function normalizePhone(input: string): string | null {
  const raw = input.trim();
  if (!ALLOWED.test(raw)) return null;
  const digits = raw.replace(/\D/g, "");
  if (digits.length === 11 && (digits[0] === "7" || digits[0] === "8")) return `+7${digits.slice(1)}`;
  if (digits.length === 10) return `+7${digits}`;
  return null;
}
